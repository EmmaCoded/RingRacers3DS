#!/bin/bash
# Builds Ring Racers 3DS, checks for errors and copies the .3dsx to Azahar.
# Usage (from devkitPro's MSYS2):  bash tools/build3ds.sh   (needs RR_AZAHAR, see tools/rr_paths.py)
# Optional: bash build3ds.sh clean   -> deletes build/ and reconfigures from scratch
# "3dsxonly" (build only), "assetsonly" (only copy assets to the SD), "both" (default)
# By default: .3dsx WITHOUT RomFS + assets synced to the Azahar SD (fast).
# Optional: bash build3ds.sh romfs    -> embeds the assets INSIDE the .3dsx (RomFS),
# like a real 3DS game (final version only). They can be combined: bash build3ds.sh clean romfs

REPO=${RR_REPO:+$(cygpath -u "$RR_REPO")}; [ -z "$REPO" ] && REPO=$(cd "$(dirname "$0")/.." && pwd)
[ -z "$RR_AZAHAR" ] && { echo "XX Set RR_AZAHAR to the Azahar folder (see tools/rr_paths.py)"; exit 1; }
WORK=$(cygpath -u "${RR_WORK:-$REPO/work}")
TEXROOT="$WORK/textures3ds"
AZAHAR_3DS="$(cygpath -u "$RR_AZAHAR")/user/sdmc/3ds/RingRacers3ds"   # the whole game in sdmc:/3ds/RingRacers3ds
LOG=/tmp/build.log

cd "$REPO" || { echo "$REPO does not exist"; exit 1; }
# the 3DS is built in the devkitPro MSYS2 window (UCRT64 is for the PC only)
if [ ! -d /opt/devkitpro ] || ! command -v make >/dev/null; then
	echo "XX This is not a devkitPro window. Open 'MSYS2' from devkitPro (C:\\devkitPro\\msys2\\msys2.exe) and run this there."; exit 1
fi

CLEAN=0; ROMFS=0; DO_3DSX=1; DO_ASSETS=1
for a in "$@"; do [ "$a" = "clean" ] && CLEAN=1; [ "$a" = "romfs" ] && ROMFS=1
	# "3dsxonly" = builds and does not touch assets; "assetsonly" = only copies assets; "both" (default)
	[ "$a" = "3dsxonly" ] && DO_ASSETS=0; [ "$a" = "assetsonly" ] && DO_3DSX=0; done

if [ $DO_3DSX = 0 ] && [ $ROMFS = 0 ]; then
	ASSETS_ONLY=1
else
	ASSETS_ONLY=0
fi

if [ $ASSETS_ONLY = 0 ]; then
if [ $CLEAN = 1 ] || [ ! -f build/Makefile ]; then
	echo ">> Configuring from scratch..."
	rm -rf build && mkdir build && cd build || exit 1
	cmake .. -DCMAKE_TOOLCHAIN_FILE=/opt/devkitpro/cmake/3DS.cmake -G "Unix Makefiles" \
		-DSRB2_CONFIG_ENABLE_DISCORDRPC=OFF -DSRB2_CONFIG_ENABLE_WEBM_MOVIES=OFF \
		-DCMAKE_DEPENDS_USE_COMPILER=OFF -DSRB2_SDL2_EXE_NAME=ringracers -DSRB2_CONFIG_HWRENDER=ON > /tmp/config.log 2>&1
	if [ $? -ne 0 ]; then
		echo "XX CMake configuration failed:"; tail -30 /tmp/config.log; exit 1
	fi
	cd "$REPO"
fi

# if an .elf was left empty (2 builds at once), make thinks it is up to date: delete it
[ -s build/bin/ringracers.elf ] || rm -f build/bin/ringracers.elf
# version visible in the game (bottom screen + log). Increments by 1 on every build.
VN=$(cat src/rr_version.txt 2>/dev/null | tr -d "
 "); case "$VN" in ''|*[!0-9-]*) VN=-1;; esac
VN=$((VN+1)); echo "$VN" > src/rr_version.txt
printf '// rr_version.h - generated by tools/build3ds.sh (do NOT edit by hand). Bumped by 1 on every build.
#define RR3DS_VERSION "1.0.%s"
' "$VN" > src/rr_version.h
echo ">> Version 1.0.$VN"
echo ">> Building (do not close this window)..."
make -C build -j$(nproc) > "$LOG" 2>&1   # all cores (before 4)
RES=$?
if [ $RES -ne 0 ]; then
	echo "XX Build failed (code $RES). Errors:"
	grep -n "error:\|undefined reference\|multiple definition\|cannot find" "$LOG" | head -40
	echo "--- end of log ---"; tail -15 "$LOG"
	exit 1
fi
echo "OK Build succeeded"
fi

if [ $ROMFS = 1 ]; then
	# RomFS = build/romfs folder glued inside the .3dsx (read-only).
	# Only what the game loads on 3DS (no music/sounds: there is no audio yet).
	echo ">> Building RomFS with the assets..."
	RF=build/romfs
	mkdir -p "$RF/data"
	cp -u assets3ds/3ds.pk3 "$RF/data/" || exit 1
	cp -u "$AZAHAR_3DS/bios.pk3" "$RF/" || { echo "XX missing bios.pk3 in $AZAHAR_3DS"; exit 1; }
	for f in scripts.pk3 gfx.pk3 ringracers_3ds.pk3 ringracers_3ds_defs.pk3 chars_3ds.pk3 maps.pk3 unlocks.pk3; do
		cp -u "$AZAHAR_3DS/data/$f" "$RF/data/" || { echo "XX missing $f in $AZAHAR_3DS/data"; exit 1; }
	done
	# audio already converted to DSP-ADPCM (tools/convert_audio.py)
	# the only copy of the 3DS audio is Azahar's (audio3ds was deleted: it was a duplicate)
	AUD="$AZAHAR_3DS"
	if [ -f "$AUD/sfx.rrp" ]; then
		mkdir -p "$RF/mus"
		cp -u "$AUD/sfx.rrp" "$RF/"
		cp -u "$AUD"/mus/*.rrm "$RF/mus/" 2>/dev/null
		echo "   Audio: sfx.rrp + $(ls "$RF/mus" | wc -l) songs"
	else
		echo "   (no audio: $AUD does not exist)"
	fi
	# precomputed blend tables (created by the game the first time in sdmc:/3ds/ringracers/)
	cp -u "$AZAHAR_3DS"/cache/blend_*.bin "$RF/" 2>/dev/null && echo "   Blend tables: yes"
	cp -u "$AZAHAR_3DS/data/thumbnails_3ds.bin" "$RF/" 2>/dev/null && echo "   80x50 thumbnails: yes"
	# ETC1/ETC1A4 textures (tools/convert_etc1.py)
	ETC=$TEXROOT/ringracers_3ds_etc.bin
	if [ -f "$ETC" ]; then
		cp -u $TEXROOT/ringracers_3ds_etc*.bin "$RF/"
		echo "   ETC1 textures: yes"
	else
		echo "   (no ETC1 textures: $ETC does not exist)"
	fi
	# large textures downscaled to 256 (tools/convert_small.py, run by rrbench)
	SMALL=$TEXROOT/ringracers_3ds_small.bin
	if [ -f "$SMALL" ]; then cp -u "$SMALL" "$RF/"; echo "   Small textures: yes"; else echo "   (no small textures: $SMALL does not exist)"; fi
	cp -u $TEXROOT/rr3ds_etcpal_*.bin "$RF/" 2>/dev/null && echo "   ETC1 custom palettes: yes"
	cp -u $TEXROOT/ringracers_3ds_spr.bin "$RF/" 2>/dev/null && echo "   ETC sprites: yes"
	echo "   RomFS: $(du -sh "$RF" | cut -f1)"
	# 3dsxtool requires an SMDH (icon + name) when it carries RomFS
	smdhtool --create "Ring Racers 3DS" "A Ring Racers 3DS port - v1.0.$VN" "Kart Krew (port)" \
		assets3ds/icon48.png build/bin/ringracers.smdh || { echo "XX smdhtool failed"; exit 1; }
	3dsxtool build/bin/ringracers.elf build/bin/ringracers.3dsx --smdh=build/bin/ringracers.smdh --romfs="$RF" || { echo "XX 3dsxtool failed"; exit 1; }
else
	# development mode (default): .3dsx WITHOUT RomFS. Assets are read from the Azahar SD
	# (the game already looks there if there is no RomFS). cp -u = only copies what is new/changed (fast).
	if [ $DO_ASSETS = 1 ]; then
	echo ">> No RomFS: syncing assets to Azahar's SD..."
	SD_DATA="$AZAHAR_3DS/data"; mkdir -p "$SD_DATA" "$AZAHAR_3DS/mus" "$AZAHAR_3DS/cache"
	# audio now lives only in Azahar (it is not copied from anywhere)
	if [ -f "$AZAHAR_3DS/sfx.rrp" ]; then echo "   Audio: sfx.rrp + $(ls "$AZAHAR_3DS/mus" | wc -l) songs (in Azahar)"
	else echo "   (no audio in $AZAHAR_3DS: run tools/convert_audio.py)"; fi
	TEX=$TEXROOT
	if ls "$TEX"/ringracers_3ds_etc*.bin >/dev/null 2>&1; then
		cp -u "$TEX"/ringracers_3ds_etc*.bin "$SD_DATA/"; echo "   ETC1 textures: yes"
	else echo "   (no ETC1 textures in $TEX)"; fi
	if [ -f "$TEX/ringracers_3ds_small.bin" ]; then
		cp -u "$TEX/ringracers_3ds_small.bin" "$SD_DATA/"; echo "   Small textures: yes"
	else echo "   (no small textures in $TEX)"; fi
	if ls "$TEX"/rr3ds_etcpal_*.bin >/dev/null 2>&1; then
		cp -u "$TEX"/rr3ds_etcpal_*.bin "$SD_DATA/"; echo "   ETC1 custom palettes: $(ls "$TEX"/rr3ds_etcpal_*.bin | wc -l)"; fi
	if [ -f "$TEX/ringracers_3ds_spr.bin" ]; then
		cp -u "$TEX/ringracers_3ds_spr.bin" "$SD_DATA/"; echo "   ETC sprites: yes"
	else echo "   (no ETC sprites in $TEX)"; fi
	# blend_*.bin and the pk3 files already live on the SD (sdmc:/3ds/ringracers and sdmc:/3ds/data)
	else echo ">> 3dsxonly: assets untouched"; fi
	if [ $ASSETS_ONLY = 1 ]; then echo "OK Assets ready (nothing was built)"; exit 0; fi
	# icon + name + version shown in the Homebrew Launcher (SMDH)
	smdhtool --create "Ring Racers 3DS" "A Ring Racers 3DS port - v1.0.$VN" "Kart Krew (port)" \
		assets3ds/icon48.png build/bin/ringracers.smdh || { echo "XX smdhtool failed"; exit 1; }
	3dsxtool build/bin/ringracers.elf build/bin/ringracers.3dsx --smdh=build/bin/ringracers.smdh || { echo "XX 3dsxtool failed"; exit 1; }
fi
mkdir -p "$AZAHAR_3DS/data"
cp build/bin/ringracers.3dsx "$AZAHAR_3DS/" || { echo "XX Could not copy to Azahar"; exit 1; }
cp assets3ds/3ds.pk3 "$AZAHAR_3DS/data/" || { echo "XX Could not copy 3ds.pk3"; exit 1; }
touch "$AZAHAR_3DS/fixed_log"   # in Azahar the log has a fixed name
rm -f "$AZAHAR_3DS/ringracers_log.txt"   # clean log for the next test

echo "OK Done: $(stat -c '%s bytes, %y' "$AZAHAR_3DS/ringracers.3dsx")"

