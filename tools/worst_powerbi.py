# worst_powerbi.py - builds ONE Power Query (M) file with the worst_maps.csv data EMBEDDED.
# No need for the CSV or the Excel alongside: it is pasted into Power BI and done.
# Usage:  py tools\worst_powerbi.py
# Output: <RR_LOGS>\worst_maps_powerbi.m
# In Power BI: Get data > Blank query > Advanced editor > delete everything > paste the .m content > Done > Close & apply.
# Run this script again when more maps have been measured (and repeat the paste).
# Locations come from rr_paths.py (environment variables RR_LOGS...).
import os, sys, csv
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rr_paths as P

LOGS = P.LOGS
CSV = os.path.join(LOGS, "worst_maps.csv")
OUT = os.path.join(LOGS, "worst_maps_powerbi.m")
NUM = ["tics", "tic_avg", "tic_p95", "tic_p99", "tic_max", "worst_sec", "frame_avg", "frame_p95", "frame_max",
       "draw_avg", "draw_p95", "draw_max", "mobjs_avg", "mobjs_max"]


def mval(field, v):
    v = (v or "").strip()
    if field in NUM:
        return v if v else "null"
    return '"' + v.replace('"', '""') + '"'


def main():
    with open(CSV, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    fields = ["map", "status"] + NUM + ["date"]
    types = ", ".join('{"%s", %s}' % (c, "type number" if c in NUM else "type text") for c in fields)
    lines = []
    for r in rows:
        lines.append("        {" + ", ".join(mval(c, r.get(c)) for c in fields) + "}")
    m = ["let",
         "    // Embedded data (worst_maps.csv, %d maps). Generated by tools\\worst_powerbi.py" % len(rows),
         "    Source = #table(",
         "        {" + ", ".join('"%s"' % c for c in fields) + "},",
         "        {",
         ",\n".join(lines),
         "        }",
         "    ),",
         "    Typed = Table.TransformColumnTypes(Source, {%s})," % types,
         "    // Budget: 1000/35 = 28.57 ms per tic. How many times each map exceeds it (worst_sec / 28.57).",
         '    WithBudget = Table.AddColumn(Typed, "budget_ms", each 1000/35, type number),',
         '    WithTimes = Table.AddColumn(WithBudget, "times_worst_sec", each if [worst_sec] = null then null else [worst_sec] / (1000/35), type number),',
         '    WithTimesAvg = Table.AddColumn(WithTimes, "times_tic_avg", each if [tic_avg] = null then null else [tic_avg] / (1000/35), type number),',
         '    WithFps = Table.AddColumn(WithTimesAvg, "fps_avg", each if [frame_avg] = null or [frame_avg] = 0 then null else 1000 / [frame_avg], type number),',
         '    Sorted = Table.Sort(WithFps, {{"worst_sec", Order.Descending}})',
         "in",
         "    Sorted"]
    with open(OUT, "w", newline="", encoding="utf-8") as f:
        f.write("\n".join(m) + "\n")
    print("== %d maps -> %s" % (len(rows), OUT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
